        'test "$(grep -c "^bsl_region_.*() {\$" /tmp/loc.fn)" = 3 && . /tmp/loc.fn && for l in '"$BSL_LANGS"'; do loc=$(bsl_region_lang_locale "$l"); printf "%s %s\n" "$l" "${loc:--}"; done | cmp -s - /tmp/loc.map'
    # Last, as it writes machine-ids: what a device runs at its first desktop start, in that order. There every file
    # belongs to the app's one real uid, and termux proot lifts permissions only for fake root (fake_id0: euid 0).
    # 1. The session's root part, before `su - $U`, as fake root: `mkdir -p /run/dbus /var/lib/dbus` and
    #    `dbus-uuidgen --ensure`. Modeled as Docker's root (fake root is let through as root is). dbus finds no id
    #    (/etc/machine-id absent, its tmpfiles link /var/lib/dbus/machine-id -> /etc/machine-id dangling), makes one and
    #    saves it to /var/lib/dbus/machine-id through a temporary file renamed over the link: a file, and still no
    #    /etc/machine-id.
    # 2. The SESSION's two lines, after `su - $U`, as fake uid 1000, where the owner's mode bits decide. Modeled: uid
    #    1000 owns /etc, /var/lib/dbus and their files, and the lines run as uid 1000 through util-linux's own setpriv
    #    (/usr/bin: the one in /usr/local/bin is the proot stub, which drops the flags). Docker's root would write
    #    anything (DAC override), which is how a 0444 file once passed here. The first line writes a NEW id to
    #    /etc/machine-id; the second sees dbus's file and keeps it.
    # So a device ends with two different ids: libdbus and GDBus read /var/lib/dbus first, PulseAudio and sd_id128 read
    # /etc. Debian's devices end the same way (empty /etc/machine-id, no /var/lib/dbus file, the same lines in the same
    # order), so it is the session's known behavior (plan 5.12), not this image's; the checks assert each half and the
    # log says whether the two match, never that they must.
    S=/usr/lib/breadstick/start-desktop-x11.sh
    grep -Fx -e 'mkdir -p /run/dbus /var/lib/dbus' -e 'dbus-uuidgen --ensure 2>/dev/null || true' "$S" > /tmp/mid-root.sh
    grep -E '^\[ -s /(etc|var/lib/dbus)/machine-id \]' "$S" > /tmp/mid.sh
    chmod 0644 /tmp/mid-root.sh /tmp/mid.sh
    check "the session's root part (dbus-uuidgen --ensure, as fake root) saves dbus an id of its own in a file, and makes no /etc/machine-id" sh -c \
        'test "$(sed -n 1p /tmp/mid-root.sh)" = "mkdir -p /run/dbus /var/lib/dbus" && test "$(sed -n 2p /tmp/mid-root.sh)" = "dbus-uuidgen --ensure 2>/dev/null || true" && test "$(wc -l < /tmp/mid-root.sh)" = 2 \
         && test ! -e /etc/machine-id && test ! -e /var/lib/dbus/machine-id && sh /tmp/mid-root.sh \
         && test -f /var/lib/dbus/machine-id && test ! -L /var/lib/dbus/machine-id && grep -Eqx "[0-9a-f]{32}" /var/lib/dbus/machine-id \
         && test ! -e /etc/machine-id && test ! -L /etc/machine-id && cp -p /var/lib/dbus/machine-id /tmp/mid.dbus'
    chown 1000:1000 /etc /var/lib/dbus
    chown -h 1000:1000 /var/lib/dbus/machine-id 2>/dev/null || true
    # The lines' own `|| true` hides a refused write, so the run leaves who ran them in /tmp/mid.who, read after.
    MIDRUN='rm -f /tmp/mid.who && /usr/bin/setpriv --reuid 1000 --regid 1000 --clear-groups sh -c "id -u > /tmp/mid.who && sh /tmp/mid.sh" && test "$(cat /tmp/mid.who)" = 1000'
    # Control: systemd's empty 0444 file, owned by the same uid, refuses the write (the model is a real one).
    check "control: an empty 0444 /etc/machine-id stays empty when the lines run as the Linux user" sh -c \
        "touch /etc/machine-id && chmod 0444 /etc/machine-id && chown 1000:1000 /etc/machine-id && $MIDRUN && test -f /etc/machine-id && test ! -s /etc/machine-id && cmp -s /var/lib/dbus/machine-id /tmp/mid.dbus"
    rm -f /etc/machine-id
    check "the session's machine-id lines, run as the Linux user (uid 1000, not root) after it, write /etc/machine-id and keep dbus's file" sh -c \
        "test \"\$(wc -l < /tmp/mid.sh)\" = 2 && test ! -e /etc/machine-id && $MIDRUN && grep -Eqx '[0-9a-f]{32}' /etc/machine-id && test \"\$(stat -c %u /etc/machine-id)\" = 1000 \
         && test -f /var/lib/dbus/machine-id && test ! -L /var/lib/dbus/machine-id && cmp -s /var/lib/dbus/machine-id /tmp/mid.dbus"
    if cmp -s /etc/machine-id /var/lib/dbus/machine-id; then echo "     /etc/machine-id and /var/lib/dbus/machine-id hold the same id"
    else echo "     /etc/machine-id and /var/lib/dbus/machine-id hold two different ids (the session's known behavior, as on Debian: plan 5.12)"; fi
    echo "     the largest packages (installed size), for the record:"
    pacman -Qi 2>/dev/null | awk -F': ' '/^Name/ { n = $2 } /^Installed Size/ { split($2, a, " "); v = a[1]; u = a[2]
