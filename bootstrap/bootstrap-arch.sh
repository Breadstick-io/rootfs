# docker export writes /.dockerenv, an empty /etc/hostname (Arch's filesystem package has none) and empty files at
# etc/hosts and etc/resolv.conf over the image's. Left out or put back (argv[1], argv[2]: the package's own files, copied
# out of the bake as etc/*.bsl-orig, which are left out too). Every name gets ./ in front, as in the Debian images;
# / and /run are 0755 (the app writes /run/bsl; the bootstrap tarball's are 0555, its build's mount points).
# The /etc/mtab link gets the package's target and time back (argv[3]: "<target> <mtime>").
import io, os, sys, tarfile
put = {"etc/hosts": sys.argv[1], "etc/resolv.conf": sys.argv[2]}
put = {k: (open(v, "rb").read(), int(os.stat(v).st_mtime)) for k, v in put.items()}
mtab_target, mtab_time = open(sys.argv[3]).read().split()
DROP = {".dockerenv", "bake.sh", "etc/hostname", "etc/hosts.bsl-orig", "etc/resolv.conf.bsl-orig", "etc/mtab.bsl-orig",
        "etc/pacman.conf.bsl-new"}
DROP_TOP = {"bsl-stage", "bsl-key"}
src = tarfile.open(fileobj=sys.stdin.buffer, mode="r|")
dst = tarfile.open(fileobj=sys.stdout.buffer, mode="w|", format=tarfile.PAX_FORMAT)
seen = set()
# The top folder first, at 0755 (the export's own, if any, is left out).
top = tarfile.TarInfo("./")
top.type, top.mode, top.uid, top.gid, top.uname, top.gname = tarfile.DIRTYPE, 0o755, 0, 0, "root", "root"
import time
top.mtime = int(time.time())
dst.addfile(top)
def dotted(n):
    n = n[2:] if n.startswith("./") else n.lstrip("/")
    return n.rstrip("/")
