reject() {  # $1 = the image as written (<name>.unchecked), $2 = why: it becomes <name>.rejected, and the bake fails
  mv -f "$1" "${1%.unchecked}.rejected"
  echo "ERROR: $2; the image is now $(basename "${1%.unchecked}").rejected" >&2
  exit 1
}
OVER_LIMIT=()
verify_image() {  # $1 = base|desktop, $2 = tarball (written as $2.unchecked, renamed $2 when it passes)
  local t="$2.unchecked" v="$PREFIX-verify-$1-$STAMP-$$" img="$PREFIX-verify:$1-$STAMP-$$" why
  log "checking $(basename "$2")"
  if why="$(bsl_arch_size_check "$t")"; then
    log "$why"
  elif [ "${OVER_CACHE_LIMIT:-}" = keep ]; then
    log "WARNING: $why (kept: OVER_CACHE_LIMIT=keep)"
    OVER_LIMIT+=("$2")
  else
    reject "$t" "$why (OVER_CACHE_LIMIT=keep keeps it, for a local measurement only)"
  fi
  zstd -dc "$t" | tar tvf - > "$WORK/list" 2>/dev/null || reject "$t" "the image does not list"
  why="$(bsl_arch_listing_check "$WORK/list")" || reject "$t" "$(echo "$why" | paste -sd ';' - | sed 's/;/; /g')"
  log "listing: $(grep -c . "$WORK/list") entries, $(grep -c '^h' "$WORK/list") hard links"
  rm -f "$WORK/list"
  zstd -dc "$t" | tar xOf - ./etc/pacman.conf > "$WORK/pacman.conf" || reject "$t" "no /etc/pacman.conf in the image"
  zstd -dc "$t" | tar xOf - ./etc/pacman.d/mirrorlist > "$WORK/mirrorlist" || reject "$t" "no mirrorlist in the image"
  why="$(bsl_arch_pacman_conf_check "$WORK/pacman.conf" "$WORK/mirrorlist")" || reject "$t" "$(echo "$why" | paste -sd ';' - | sed 's/;/; /g')"
  # /etc/hosts and /etc/resolv.conf are Docker's mounts in the check's container, so they are compared here, as written,
  # with the filesystem package's own (what the bake copied out of it).
  zstd -dc "$t" | tar xOf - ./etc/hosts > "$WORK/img-hosts" && cmp -s "$WORK/img-hosts" "$WORK/hosts" \
    || reject "$t" "/etc/hosts is not the filesystem package's"
  zstd -dc "$t" | tar xOf - ./etc/resolv.conf > "$WORK/img-resolv.conf" && cmp -s "$WORK/img-resolv.conf" "$WORK/resolv.conf" \
    || reject "$t" "/etc/resolv.conf is not the filesystem package's"
  IMAGES+=("$img")
  zstd -dc "$t" | docker import --platform "linux/$ARCH" - "$img" >/dev/null
  CONTAINERS+=("$v")
  docker create --name "$v" --platform "linux/$ARCH" --network none \
    -v "$WORK/check.sh:/check.sh:ro" -v "$WORK/bsl-os.sh:/bsl-os.sh:ro" -e BSLOS=$([ "$1" = base ] && echo /bsl-os.sh || echo /usr/lib/breadstick/bsl-os.sh) \
    "$img" sh /check.sh "$1" >/dev/null
  docker start -a "$v" || reject "$t" "$(basename "$2") failed its checks"
  docker rm -f "$v" >/dev/null
  docker rmi -f "$img" >/dev/null
  mv -f "$t" "$2"
  log "$(basename "$2") passed ($(took))"
}
write_manifest() {  # $1 = base|desktop, $2 = tarball
  [ -n "${MANIFEST_DIR:-}" ] || return 0
  mkdir -p "$MANIFEST_DIR"
  local m="manifest-archlinux-$ARCH.json"
  [ "$1" = desktop ] && m="manifest-archlinux-$ARCH-desktop.json"
  printf '{\n  "version": "%s",\n  "file": "%s",\n  "size": %s,\n  "sha256": "%s",\n  "arch": "%s",\n  "distro": "archlinux"\n}\n' \
    "$STAMP" "$(basename "$2")" "$(stat -c %s "$2")" "$(sha256sum "$2" | cut -d' ' -f1)" "$ARCH" > "$MANIFEST_DIR/$m"
  log "local manifest $MANIFEST_DIR/$m"
}

