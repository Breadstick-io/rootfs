#!/usr/bin/env bash
# The Arch based system's images (4.0, x86-64 only; plan Android/docs/4.0/multi-distro.md 5.12, decision 11).
# LOCAL ONLY: nothing here uploads anything, and no manifest is written anywhere a released app (or the CDN) reads.
#
#   [RELEASE=YYYY.MM.DD] [PACMAN_STAGE=/abs/stage] [PKGROOT=/abs/packages] rootfs/bootstrap/bootstrap-arch.sh [base|desktop|both]
#
# 1. The official bootstrap tarball, archlinux-bootstrap-<release>-x86_64.tar.zst, from the geo mirror Arch's download
#    page names (https://archlinux.org/download/), into dist/cache/archlinux/<release>/ (git-ignored); its detached
#    signature from archlinux.org itself, never a mirror (Arch's wiki, "Install Arch Linux from existing Linux"). The
#    release key is fetched by WKD for pierre@archlinux.org, and the signature must be a good one by the key whose
#    fingerprint is pinned below (copied from the download page, 2026-11-13); the tarball's sha256 must also be the one
#    archlinux.org's sha256sums.txt gives. Any mismatch refuses, and a cached tarball that fails is renamed .bad.
#    Not the archlinux Docker image: its pacman.conf drops every locale, man page and translation (NoExtract).
# 2. Unpacked by Docker, not on this host: the tarball is rewritten entry by entry (root.x86_64/ taken off the names,
#    owners, modes, hard links and links as they are) into `docker import`, which unpacks it as root with numeric
#    owners. This host has no bsdtar, and GNU tar as an unprivileged user cannot keep root's owners, setuid bits or
#    device nodes. The bake then runs in that image (amd64, under qemu-user 10 on this arm64 host:
#    AutoBuild/tools/qemu-x86_64-setup.sh), with the network and never the gpg-agent socket (nothing is signed here).
# 3. base: the mirrorlist (Arch's own pkgbuild.com mirrors, then tier 1 mirrors; the shipped one has no active line),
#    pacman.conf (DisableSandbox, DownloadUser commented out, [breadstick] after core, extra and multilib with
#    SigLevel = Required DatabaseRequired and Server = https://pacman.breadstick.io/$repo/os/$arch), pacman-key --init
#    and --populate archlinux, Breadstick's archive key added from bootstrap/breadstick-archive-keyring.gpg only
#    after its fingerprint is checked (EABBC4B5F0BD78B405AF005FF02A2D085AC691BC) and signed locally, two systemd hooks
#    masked (binfmt and modules-load: neither has anything to do under proot), pacman -Syu, the base set (what
#    bootstrap-debian.sh's INCLUDE gives Debian), breadstick-keyring, and the proot stubs (below).
#    desktop: breadstick-desktop and breadstick-print, Chromium (decision 11: the image ships a browser, because an
#    install on Arch is a whole-system upgrade, which only Updates runs), set up by Breadstick's install-browser.sh
#    with no choice (its default), and the desktop-ok marker the app looks for.
#    Both: Arch's own modes kept (sudo 4755 and /root 0750, as Arch packages them: plan 5.12), every locale and
#    translation kept (no NoExtract; locales are generated by the session when the user picks a language, as on
#    Debian's images), no /etc/machine-id (Debian's images ship an EMPTY 0644 one and Fedora's keep theirs that way;
#    either state works: the session's dbus-uuidgen writes each device its own as the Linux user, and on a device every
#    file belongs to the app's one uid and proot lifts permissions only for fake root, so the owner's mode bits decide.
#    The empty 0444 file systemd leaves would refuse that write; so this image ships none, in an /etc at 0755) and
#    systemd's random seed removed, pacman's keyring without its master key's secret half (every device made from
#    the image would share it, and whoever has the image could certify keys those devices trust: Arch's own Docker
#    image removes it too; see "Open" below), no sync databases (they go stale, and Updates syncs), pacman -Scc, the
#    bake's own log, /tmp and /var/tmp emptied.
#    The proot stubs, as Debian's provision.sh installs them, but in /usr/local/bin only: systemctl and
#    systemd-tmpfiles (no init, nothing to start), setpriv (proot cannot change the real uid: it drops the flags and
#    runs the program). Not over /usr/bin: those are systemd's and util-linux's files (pacman -Qkk would report them,
#    and every update puts them back), and Arch's alpm hooks call /usr/bin/systemctl and /usr/bin/systemd-tmpfiles by
#    path anyway. No systemd-sysusers shim: Arch's base has the real one, which the sysusers hook runs by path, and
#    Phase 0 ran it under proot (Fedora's). No user is made: the app's setup-user.sh does that at first run.
# 4. The image: `docker export` of the step's container, rewritten as the Debian images are written (./ names,
#    numeric owners, hard links kept, zstd level 19), minus Docker's own files (/.dockerenv, /etc/hostname, the
#    mounts), with the filesystem package's /etc/hosts, /etc/resolv.conf and /etc/mtab link put back (docker export
#    writes empty files and a link to /proc/mounts), / and /run at 0755. /usr/lib/os-release is the filesystem
#    package's again (the bootstrap tarball's carries archiso's IMAGE_ID and IMAGE_VERSION lines); Breadstick's identity
#    is written by the session at the first start (bsl_os_identity, plan 5.11), never by the bake. Named archlinux-rolling-amd64[-desktop]-<stamp>.tar.zst (plan 5.12) in dist/ (git-ignored).
#    Written as <name>.unchecked, renamed <name> only when every check passed (arch-image-checks.sh, then the image
#    imported and checked with no network), else <name>.rejected and the bake fails. An image at or over 512,000,000
#    bytes is refused (Cloudflare's per-file cache limit, plan 5.4); OVER_CACHE_LIMIT=keep keeps it for a local
#    measurement only, with a warning.
#
# PACMAN_STAGE: until pacman.breadstick.io serves packages, a local stage made by Apt's pacman/stage-pacman-repo.sh
# (TEST=1 for [breadstick-test]) is the only repository there is. It is mounted read-only at /bsl-stage and used ONLY
# by the bake's own pacman configuration (/tmp, removed after); the image's pacman.conf names pacman.breadstick.io
# throughout, and the checks refuse any local URL in it. The packages then come from a local stage, so those images are
# named archlinux-rolling-...-staged-<stamp>.tar.zst and must never be published.
#
# MANIFEST_DIR (optional): write manifest-archlinux-amd64[-desktop].json for each image there (version, file, size,
# sha256, arch, distro), the names the 4.0 app reads (RootfsDownloader.manifestName), for a LOCAL check. Refused inside
# the workspace's mirror and anywhere under AutoBuild/dist.
# CONTAINER_PREFIX names the containers and images this makes (default bsl-arch-bake); all are removed at exit.
# FETCH_ONLY=1 downloads (or takes from the cache) and verifies the bootstrap tarball, then stops.
#
# The image ships pacman's keyring with Breadstick's and Arch's keys signed by a master key whose secret half is gone,
# which verifies everything it holds but cannot sign a key (every pacman-key --populate fails without one). A device
# makes its own master key before its first Updates: breadstick-session's bsl_pacman_keyring_init (pacman-key --init,
# once), called by the app's setup-user.sh and by the session start (plan 5.12; the Arch session gate, 2026-11-14).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
WHAT="${1:-both}"
case "$WHAT" in base|desktop|both) ;; *) echo "usage: $0 [base|desktop|both]" >&2; exit 1 ;; esac
case "$(uname -m)" in aarch64|arm64) HOST=arm64 ;; x86_64) HOST=amd64 ;; *) echo "ERROR: unknown host" >&2; exit 1 ;; esac
ARCH=amd64   # x86-64 only in 4.0 (plan 5.12); there is no official aarch64 port.
[ "${ARCH_OVERRIDE:-amd64}" = amd64 ] || { echo "ERROR: the Arch based system is x86-64 only" >&2; exit 1; }
OUT_DIR="${OUT_DIR:-$ROOT/dist}"
CACHE_ROOT="${CACHE_ROOT:-$ROOT/dist/cache/archlinux}"
STAMP="${STAMP:-$(date -u +%Y%m%d%H%M)}"
case "$STAMP" in [0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]) ;; *) echo "ERROR: STAMP must be YYYYMMDDHHMM" >&2; exit 1 ;; esac
LEVEL="${BAKE_ZSTD_LEVEL:-19}"
case "${OVER_CACHE_LIMIT:-}" in ''|keep) ;; *) echo "ERROR: OVER_CACHE_LIMIT is keep or unset" >&2; exit 1 ;; esac
PREFIX="${CONTAINER_PREFIX:-bsl-arch-bake}"
case "$PREFIX" in bsl-[a-z0-9-]*) ;; *) echo "ERROR: CONTAINER_PREFIX must start with bsl-" >&2; exit 1 ;; esac
# shellcheck source=arch-image-checks.sh
. "$HERE/arch-image-checks.sh"
[ "$BSL_CACHE_LIMIT" -le 512000000 ] 2>/dev/null || { echo "ERROR: BSL_CACHE_LIMIT may only lower the 512,000,000-byte limit" >&2; exit 1; }

# Arch's release signing key (Pierre Schmitz), as archlinux.org/download names it on 2026-11-13 ("PGP fingerprint:
# 0x54449A5C", the full fingerprint in the page's keyserver link). The tarball must carry a good signature by THIS key;
# the key itself comes from WKD, never from the page or a mirror.
ARCH_RELEASE_FPR=3E80CA1A8B89F69CBA57D98A76A5EF9054449A5C
ARCH_RELEASE_EMAIL=pierre@archlinux.org
KEY="$HERE/breadstick-archive-keyring.gpg"
FPR=EABBC4B5F0BD78B405AF005FF02A2D085AC691BC
UA="breadstick-bake"
log() { printf '\033[1;34m[bake-arch]\033[0m %s\n' "$*"; }
T0=$(date +%s)
took() { echo "$(( $(date +%s) - T0 )) s"; }

[ "$(gpg --batch --show-keys --with-colons "$KEY" 2>/dev/null | grep -c '^pub:')" = 1 ] \
  && gpg --batch --show-keys --with-colons "$KEY" 2>/dev/null | grep -q "^fpr:::::::::$FPR:" \
  || { echo "ERROR: $KEY is not exactly the archive key $FPR" >&2; exit 1; }

STAGED=""
STAGE_REPO=""
MOUNT=()
if [ -n "${PACMAN_STAGE:-}" ]; then
  case "$PACMAN_STAGE" in /*) ;; *) echo "ERROR: PACMAN_STAGE must be an absolute path" >&2; exit 1 ;; esac
  for r in breadstick breadstick-test; do
    if [ -z "$STAGE_REPO" ] && [ -f "$PACMAN_STAGE/$r/os/x86_64/$r.db" ] && [ -f "$PACMAN_STAGE/$r/os/x86_64/$r.db.sig" ]; then STAGE_REPO=$r; fi
  done
  [ -n "$STAGE_REPO" ] && [ -f "$PACMAN_STAGE/breadstick-archive-keyring.gpg" ] \
    || { echo "ERROR: $PACMAN_STAGE is not a pacman stage (Apt's pacman/stage-pacman-repo.sh)" >&2; exit 1; }
  cmp -s "$PACMAN_STAGE/breadstick-archive-keyring.gpg" "$KEY" || { echo "ERROR: the stage's key is not $KEY" >&2; exit 1; }
  STAGED=1
  MOUNT=(-v "$PACMAN_STAGE:/bsl-stage:ro")
  log "NOTE: PACMAN_STAGE is a local stage ([$STAGE_REPO]): the images are named -staged- and must never be published"
fi
if [ -n "${MANIFEST_DIR:-}" ]; then
  case "$MANIFEST_DIR" in /*) ;; *) echo "ERROR: MANIFEST_DIR must be an absolute path" >&2; exit 1 ;; esac
  case "$(realpath -m "$MANIFEST_DIR")/" in
    */AutoBuild/dist/*|*/mirror/*) echo "ERROR: MANIFEST_DIR may not be under AutoBuild/dist or a mirror" >&2; exit 1 ;;
  esac
fi
BSLOS_TREE="${PKGROOT:-$ROOT/../packages}"
[ -f "$BSLOS_TREE/breadstick-session/src/lib/bsl-os.sh" ] \
  || { echo "ERROR: no bsl-os.sh in $BSLOS_TREE (set PKGROOT= to the packages tree)" >&2; exit 1; }
mkdir -p "$OUT_DIR" "$CACHE_ROOT"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"
name_of() {  # $1 = base|desktop
  local n="archlinux-rolling-$ARCH"
  [ "$1" = desktop ] && n="$n-desktop"
  [ -n "$STAGED" ] && n="$n-staged"
  echo "$OUT_DIR/$n-$STAMP.tar.zst"
}

WORK="$(mktemp -d)"
CONTAINERS=()
IMAGES=()
cleanup() {
  for c in "${CONTAINERS[@]}"; do docker rm -f "$c" >/dev/null 2>&1 || true; done
  for i in "${IMAGES[@]}"; do docker rmi -f "$i" >/dev/null 2>&1 || true; done
  rm -f "$WORK"/bake.sh "$WORK"/check.sh "$WORK"/import.py "$WORK"/export.py "$WORK"/bsl-os.sh "$WORK"/list \
    "$WORK"/hosts "$WORK"/resolv.conf "$WORK"/download.html "$WORK"/sha256sums.txt "$WORK"/release-key.pgp \
    "$WORK"/gpgv.status "$WORK"/pacman.conf "$WORK"/mirrorlist "$WORK"/mtab "$WORK"/img-hosts "$WORK"/img-resolv.conf
  rmdir "$WORK" 2>/dev/null || true
}
trap cleanup EXIT
cp "$BSLOS_TREE/breadstick-session/src/lib/bsl-os.sh" "$WORK/bsl-os.sh"
log "bsl-os.sh for the checks: $BSLOS_TREE ($(git -C "$BSLOS_TREE" rev-parse --abbrev-ref HEAD 2>/dev/null || echo '?') $(git -C "$BSLOS_TREE" rev-parse --short HEAD 2>/dev/null || echo '?'))"

# 1. The bootstrap tarball, its signature and the release key.
fetch() { curl -fsSL --proto '=https' --tlsv1.2 -A "$UA" -o "$2" "$1"; }
fetch https://archlinux.org/download/ "$WORK/download.html"
PAGE_RELEASE="$(grep -o 'href="https://archlinux\.org/iso/[0-9][0-9][0-9][0-9]\.[0-9][0-9]\.[0-9][0-9]/archlinux-bootstrap-[0-9.]*-x86_64\.tar\.zst\.sig"' "$WORK/download.html" \
  | sed 's|.*/iso/\([0-9.]*\)/.*|\1|' | sort -u)"
[ "$(printf '%s\n' "$PAGE_RELEASE" | grep -c .)" = 1 ] || { echo "ERROR: archlinux.org/download names no single bootstrap release" >&2; exit 1; }
RELEASE="${RELEASE:-$PAGE_RELEASE}"
case "$RELEASE" in [0-9][0-9][0-9][0-9].[0-9][0-9].[0-9][0-9]) ;; *) echo "ERROR: RELEASE must be YYYY.MM.DD" >&2; exit 1 ;; esac
[ "$RELEASE" = "$PAGE_RELEASE" ] || log "NOTE: RELEASE=$RELEASE, the download page's is $PAGE_RELEASE"
grep -q "Current Release:</strong> $PAGE_RELEASE" "$WORK/download.html" || log "NOTE: the page's \"Current Release\" line did not read as $PAGE_RELEASE"
grep -q 'search=0x'"$ARCH_RELEASE_FPR" "$WORK/download.html" \
  || { echo "ERROR: archlinux.org/download no longer names the release key $ARCH_RELEASE_FPR: check the new one by hand before changing the pin" >&2; exit 1; }
MIRROR="$(grep -o "href=\"https://geo\.mirror\.pkgbuild\.com/iso/$PAGE_RELEASE/\"" "$WORK/download.html" | head -n 1 | sed 's/^href="//; s/"$//')"
[ -n "$MIRROR" ] || MIRROR="https://geo.mirror.pkgbuild.com/iso/$PAGE_RELEASE/"
[ "$RELEASE" = "$PAGE_RELEASE" ] || MIRROR="https://geo.mirror.pkgbuild.com/iso/$RELEASE/"
TARNAME="archlinux-bootstrap-$RELEASE-x86_64.tar.zst"
CACHE="$CACHE_ROOT/$RELEASE"
mkdir -p "$CACHE"
TARBALL="$CACHE/$TARNAME"
if [ ! -f "$TARBALL" ]; then
  log "downloading $MIRROR$TARNAME"
  fetch "$MIRROR$TARNAME" "$TARBALL.part"
  mv -f "$TARBALL.part" "$TARBALL"
else
  log "cached: $TARBALL"
fi
fetch "https://archlinux.org/iso/$RELEASE/$TARNAME.sig" "$CACHE/$TARNAME.sig"
fetch "https://archlinux.org/iso/$RELEASE/sha256sums.txt" "$WORK/sha256sums.txt"
WKD="$(gpg-wks-client --print-wkd-url "$ARCH_RELEASE_EMAIL" 2>/dev/null || /usr/lib/gnupg/gpg-wks-client --print-wkd-url "$ARCH_RELEASE_EMAIL")"
case "$WKD" in https://*) ;; *) echo "ERROR: no WKD address for $ARCH_RELEASE_EMAIL" >&2; exit 1 ;; esac
fetch "$WKD" "$WORK/release-key.pgp"
bad_tarball() { mv -f "$TARBALL" "$TARBALL.bad"; echo "ERROR: $1; the cached tarball is now $TARBALL.bad" >&2; exit 1; }
gpg --batch --show-keys --with-colons "$WORK/release-key.pgp" 2>/dev/null | grep -q "^fpr:::::::::$ARCH_RELEASE_FPR:" \
  || { echo "ERROR: WKD for $ARCH_RELEASE_EMAIL did not give the key $ARCH_RELEASE_FPR" >&2; exit 1; }
# gpgv against the WKD keys alone; the good signature's primary key (VALIDSIG's last field) must be the pinned one.
gpgv --keyring "$WORK/release-key.pgp" --status-fd 3 "$CACHE/$TARNAME.sig" "$TARBALL" 3>"$WORK/gpgv.status" >/dev/null 2>&1 \
  || bad_tarball "$TARNAME does not carry a good signature by $ARCH_RELEASE_EMAIL's key"
SIGNER="$(awk '$1 == "[GNUPG:]" && $2 == "VALIDSIG" { print $NF }' "$WORK/gpgv.status" | sort -u)"
[ "$SIGNER" = "$ARCH_RELEASE_FPR" ] || bad_tarball "$TARNAME is signed by ${SIGNER:-nobody}, not $ARCH_RELEASE_FPR"
grep -q '^\[GNUPG:\] GOODSIG ' "$WORK/gpgv.status" || bad_tarball "gpgv reported no GOODSIG for $TARNAME"
SUM="$(sha256sum "$TARBALL" | cut -d' ' -f1)"
grep -Eq "^$SUM  $TARNAME\$" "$WORK/sha256sums.txt" || bad_tarball "$TARNAME's sha256 $SUM is not archlinux.org's"
log "bootstrap $RELEASE: $(stat -c %s "$TARBALL") bytes, signed by $SIGNER (WKD $ARCH_RELEASE_EMAIL), sha256 $SUM as archlinux.org lists it"
if [ -n "${FETCH_ONLY:-}" ]; then log "FETCH_ONLY: the bootstrap tarball is verified; nothing baked"; exit 0; fi

# 2. Into Docker as an image, root.x86_64/ taken off every name. Never unpacked on this host.
cat > "$WORK/import.py" <<'BSL_ARCH_IMPORT_9c2e'
# The bootstrap tarball's entries, root.x86_64/ taken off their names and their link targets, everything else as it is
# (owners, modes, times, hard links, xattrs). Anything outside root.x86_64/ but the release's pkglist.x86_64.txt and
# version is refused.
import sys, tarfile
P = "root.x86_64/"
src = tarfile.open(fileobj=sys.stdin.buffer, mode="r|")
dst = tarfile.open(fileobj=sys.stdout.buffer, mode="w|", format=tarfile.PAX_FORMAT)
n = 0
for m in src:
    if m.name.rstrip("/") == P.rstrip("/"):
        m.name = "."
    elif m.name.startswith(P):
        m.name = m.name[len(P):]
    elif m.name in ("pkglist.x86_64.txt", "version") and m.isreg():
        continue  # the release's package list and version, beside the tree (not part of the system)
    else:
        sys.exit("entry outside %s: %s" % (P, m.name))
    if m.islnk():
        if not m.linkname.startswith(P):
            sys.exit("hard link outside %s: %s" % (P, m.linkname))
        m.linkname = m.linkname[len(P):]
    for k in [k for k in m.pax_headers if k in ("path", "linkpath")]:
        del m.pax_headers[k]
    dst.addfile(m, src.extractfile(m) if m.isreg() else None)
    n += 1
dst.close()
print("%d entries" % n, file=sys.stderr)
BSL_ARCH_IMPORT_9c2e
BOOT_IMG="$PREFIX:bootstrap-$RELEASE-$STAMP-$$"
IMAGES+=("$BOOT_IMG")
log "importing the bootstrap tree into $BOOT_IMG"
zstd -dc "$TARBALL" | python3 -I "$WORK/import.py" | docker import --platform "linux/$ARCH" - "$BOOT_IMG" >/dev/null
[ "$(docker image inspect -f '{{.Architecture}}' "$BOOT_IMG")" = "$ARCH" ] || { echo "ERROR: $BOOT_IMG is not $ARCH" >&2; exit 1; }

# 3. The bake, run as root in the container. Its own file (no heredoc its content could end early).
cat > "$WORK/bake.sh" <<'BSL_ARCH_BAKE_9c2e'
set -eu
STEP=$1 STAGE_REPO=$2
FPR=EABBC4B5F0BD78B405AF005FF02A2D085AC691BC
PC=/etc/pacman.conf
BAKE=/tmp/bsl-bake-pacman.conf
SERVER='https://pacman.breadstick.io/$repo/os/$arch'
say() { echo "[bake] $(date -u +%H:%M:%S) $*"; }
# The bake's own pacman configuration: the image's, with [breadstick] pointed at the local stage when there is one.
# Only the bake uses it, and it is removed before the image is written.
mkbake() {
    if [ -n "$STAGE_REPO" ]; then
        awk -v r="$STAGE_REPO" '
            /^[ \t]*\[breadstick\][ \t]*$/ { print "[" r "]"; inb = 1; next }
            /^[ \t]*\[/ { inb = 0 }
            inb && /^[ \t]*Server[ \t]*=/ { print "Server = file:///bsl-stage/$repo/os/$arch"; next }
            { print }' "$PC" > "$BAKE"
        grep -qx "\[$STAGE_REPO\]" "$BAKE" && grep -qx 'Server = file:///bsl-stage/$repo/os/$arch' "$BAKE" \
            || { echo "the bake's pacman.conf does not name the stage" >&2; exit 1; }
    else
        cp "$PC" "$BAKE"
    fi
}
P="pacman --config $BAKE --noconfirm"
if [ "$STEP" = base ]; then
    [ "$(uname -m)" = x86_64 ] || { echo "not x86-64" >&2; exit 1; }
    grep -qx ID=arch /usr/lib/os-release || { echo "not Arch's os-release" >&2; exit 1; }
    say "1. the mirrorlist"
    cat > /etc/pacman.d/mirrorlist <<'BSL_ARCH_MIRRORS_9c2e'
##
## Arch Linux repository mirrorlist (Breadstick Linux, the image bake)
## Arch's own mirrors (run by Arch's DevOps team, pkgbuild.com) first, then tier 1 mirrors
## (https://archlinux.org/mirrors/tier/1/, read 2026-11-13). Reorder or replace them freely.
##

Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch
Server = https://fastly.mirror.pkgbuild.com/$repo/os/$arch
Server = https://mirrors.kernel.org/archlinux/$repo/os/$arch
Server = https://mirror.rackspace.com/archlinux/$repo/os/$arch
Server = https://ftp.halifax.rwth-aachen.de/archlinux/$repo/os/$arch
Server = https://mirrors.rit.edu/archlinux/$repo/os/$arch
BSL_ARCH_MIRRORS_9c2e
    say "2. pacman.conf"
    ! grep -Eq '^[[:space:]]*NoExtract' "$PC" || { echo "pacman.conf drops files (NoExtract): not the bootstrap's" >&2; exit 1; }
    ! grep -Eq '^[[:space:]]*\[breadstick' "$PC" || { echo "pacman.conf already has a Breadstick section" >&2; exit 1; }
    awk '{ if ($0 ~ /^[ \t]*DownloadUser[ \t]*=/) print "#" $0; else print }
         !done && /^[ \t]*\[options\][ \t]*$/ { print "# Breadstick Linux (the image bake): no download sandbox under proot."; print "DisableSandbox"; done = 1 }' \
        "$PC" > "$PC.bsl-new"
    { echo; echo "# Breadstick Linux: Breadstick's own packages, after every Arch repository."
      echo "[breadstick]"; echo "SigLevel = Required DatabaseRequired"; echo "Server = $SERVER"; } >> "$PC.bsl-new"
    cat "$PC.bsl-new" > "$PC"; rm -f "$PC.bsl-new"
    [ "$(pacman-conf --repo-list | tr '\n' ' ')" = "core extra breadstick " ] || { echo "repositories: $(pacman-conf --repo-list | tr '\n' ' ')" >&2; exit 1; }
    pacman-conf DisableSandbox | grep -qx DisableSandboxFilesystem && pacman-conf DisableSandbox | grep -qx DisableSandboxSyscalls \
        || { echo "DisableSandbox did not take" >&2; exit 1; }
    [ -z "$(pacman-conf DownloadUser)" ] || { echo "DownloadUser is still set" >&2; exit 1; }
    mkbake
    say "3. pacman's keyring, and Breadstick's key checked by fingerprint, added and signed locally"
    pacman-key --init
    pacman-key --populate archlinux
    [ "$(gpg --batch --show-keys --with-colons /bsl-key/breadstick-archive-keyring.gpg | grep -c '^pub:')" = 1 ] \
        && gpg --batch --show-keys --with-colons /bsl-key/breadstick-archive-keyring.gpg | grep -q "^fpr:::::::::$FPR:" \
        || { echo "the key file is not exactly $FPR" >&2; exit 1; }
    pacman-key --add /bsl-key/breadstick-archive-keyring.gpg
    pacman-key --lsign-key "$FPR"
    say "4. systemd's binfmt and modules-load hooks masked (alpm-hooks(5): a link to /dev/null in the hook folder)"
    mkdir -p /etc/pacman.d/hooks
    ln -sfn /dev/null /etc/pacman.d/hooks/25-systemd-binfmt.hook
    ln -sfn /dev/null /etc/pacman.d/hooks/36-systemd-modules-load.hook
    say "5. pacman -Syu, the base set and breadstick-keyring"
    $P -Syu
    $P -S --needed sudo nano less tmux curl openssh gnupg ca-certificates procps-ng shadow ncurses diffutils which
    $P -S --needed breadstick-keyring
    say "6. the proot stubs in /usr/local/bin"
    mkdir -p /usr/local/bin
    for t in systemctl systemd-tmpfiles; do
        printf '#!/bin/sh\n# Breadstick Linux: no init under proot, so nothing to start or create here.\nexit 0\n' > "/usr/local/bin/$t"
    done
