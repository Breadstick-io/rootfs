    name = dotted(m.name)
    if name in DROP or name.split("/")[0] in DROP_TOP or name == "":
        continue
    if name.startswith("dev/"):
        continue  # the runtime's device nodes and mounts; proot binds Android's /dev
    for k in [k for k in m.pax_headers if k in ("path", "linkpath")]:
        del m.pax_headers[k]
    if m.islnk():
        m.linkname = "./" + dotted(m.linkname)
    m.name = "./" + name
    if name == "run" and m.isdir():
        m.mode = 0o755
    if name == "etc/mtab":
        m.type, m.linkname, m.mtime, m.size = tarfile.SYMTYPE, mtab_target, int(mtab_time), 0
        dst.addfile(m)
        seen.add(name)
        continue
    if name in put:
        data, mtime = put[name]
        m.mtime = mtime
        for k in [k for k in m.pax_headers if k in ("size", "uid", "gid", "uname", "gname")]:
            del m.pax_headers[k]
        m.size, m.mode, m.uid, m.gid, m.uname, m.gname = len(data), 0o644, 0, 0, "root", "root"
        dst.addfile(m, io.BytesIO(data))
        seen.add(name)
        continue
    dst.addfile(m, src.extractfile(m) if m.isreg() else None)
dst.close()
missing = (set(put) | {"etc/mtab"}) - seen
if missing:
    sys.exit("not in the export: %s" % ", ".join(sorted(missing)))
BSL_ARCH_EXPORT_9c2e

run_step() {  # $1 = base|desktop, $2 = image to start from; leaves the container's name in $C
  C="$PREFIX-$1-$STAMP-$$"
  CONTAINERS+=("$C")
  log "$1 step in $C ($(took) so far)"
  docker create --name "$C" --platform "linux/$ARCH" "${MOUNT[@]}" -v "$HERE:/bsl-key:ro" -v "$WORK/bake.sh:/bake.sh:ro" \
    "$2" sh /bake.sh "$1" "$STAGE_REPO" >/dev/null
  docker start -a "$C"
  [ "$(docker inspect -f '{{.State.ExitCode}}' "$C")" = 0 ] || { echo "ERROR: the $1 step failed" >&2; exit 1; }
  log "$1 step done ($(took))"
}
export_image() {  # $1 = container, $2 = tarball
  log "exporting $1 -> $2"
  rm -f "$WORK/hosts" "$WORK/resolv.conf" "$WORK/mtab"
  docker cp "$1:/etc/hosts.bsl-orig" "$WORK/hosts"
  docker cp "$1:/etc/resolv.conf.bsl-orig" "$WORK/resolv.conf"
  docker cp "$1:/etc/mtab.bsl-orig" "$WORK/mtab"
  docker export "$1" | python3 -I "$WORK/export.py" "$WORK/hosts" "$WORK/resolv.conf" "$WORK/mtab" | zstd -q -"$LEVEL" -T0 -o "$2.part"
  zstd -q -t "$2.part"
  mv -f "$2.part" "$2.unchecked"
  log "written ($(took)): $(stat -c %s "$2.unchecked") bytes"
}

